#!/usr/bin/env python3
"""NearS audio batch runner. Stdlib only; worker imports exactly one algorithm.

Run from project root: python3 run_nears_12.py --codec mp3 --bitrate 64k
                            python3 run_nears_12.py --codec opus --bitrate 96k
                            python3 run_nears_12.py --codec none
Outputs are the normal audio artifacts generated by each algorithm.
"""
import os

# Must be set BEFORE loading numpy/scipy/numba (even in spawned workers).
for _name in (
    'OPENBLAS_NUM_THREADS', 'OMP_NUM_THREADS', 'MKL_NUM_THREADS',
    'NUMEXPR_NUM_THREADS', 'VECLIB_MAXIMUM_THREADS', 'BLIS_NUM_THREADS',
    'NUMBA_NUM_THREADS',
):
    os.environ[_name] = '1'
os.environ['MALLOC_ARENA_MAX'] = '2'
os.environ['OMP_WAIT_POLICY'] = 'PASSIVE'
os.environ['MPLBACKEND'] = 'Agg'

import argparse
import importlib
import subprocess
import sys
import time
from pathlib import Path

ALGOS = {
    '1': ('algoss.alg1_sim.script1', 'test_1_run', 'alg1_sim'),
    '2': ('algoss.alg2_wavelet.script_wavelet', 'test_2_run', 'alg2_wavelet'),
    '3': ('algoss.alg3_lossless.script_lossless', 'test_3_run', 'alg3_lossless'),
    '5': ('algoss.alg5_emd.emd_v3', 'test_5_run', 'alg5_emd'),
    '6': ('algoss.alg6_wht.wht_v3', 'test_6_run', 'alg6_wht'),
    '7': ('algoss.alg7_kra.test_realtime', 'test_7_run', 'alg7_kra'),
}


def process_one(alg, i, root, fmt, bitrate):
    module_name, function, dirname = ALGOS[alg]
    module = importlib.import_module(module_name)
    fn = getattr(module, function)
    source = root / 'dataset' / 'test_sounds' / ('test_sound%d.wav' % i)
    encrypted = root / 'algoss' / dirname / 'test_encrypted' / ('enc%d.wav' % i)
    decrypted = root / 'algoss' / dirname / 'test_decrypted' / ('dec%d.wav' % i)
    if not source.is_file():
        raise FileNotFoundError(str(source))
    encrypted.parent.mkdir(parents=True, exist_ok=True)
    decrypted.parent.mkdir(parents=True, exist_ok=True)
    decrypted.unlink(missing_ok=True)

    encrypted.with_name(
        "org_" + encrypted.name
    ).unlink(missing_ok=True)

    for suffix in (
        "_opus_decoded.wav",
        "_mp3_decoded.wav",
        "_opus_raw.wav",
        "_opus_aligned.wav",
        "_mp3_raw.wav",
        "_mp3_aligned.wav",
    ):
        encrypted.with_name(
            encrypted.stem + suffix
        ).unlink(missing_ok=True)
    org, enc, dec = map(str, (source, encrypted, decrypted))
    if alg == '6':
        fn(org, enc, dec, org_format='wav', new_format=fmt,
           codec=('libopus' if fmt == 'ogg' else 'mp3'), bitrate=bitrate)
    elif alg == '7':
        fn(org, enc, dec, org_format='wav', new_format=fmt,
           codec_bitrate=bitrate)
    else:
        fn(org, enc, dec, org_format='wav', new_format=fmt,
           codec=('libopus' if fmt == 'ogg' else 'mp3'), bitrate=bitrate)


def available_memory_bytes():
    try:
        with open('/proc/meminfo', 'r', encoding='ascii') as f:
            for line in f:
                if line.startswith('MemAvailable:'):
                    return int(line.split()[1]) * 1024
    except OSError:
        pass
    return None


def run_worker(args):
    # One worker loads only its assigned algorithm and reuses its models.
    root = Path(args.root).resolve()
    sys.path.insert(0, str(root))
    try:
        for i in map(int, args.ids.split(',')):
            process_one(args.worker, i, root, args.codec, args.bitrate)
    except BaseException:
        import traceback
        print('ERROR algorithm %s, worker ids %s' % (args.worker, args.ids),
              file=sys.stderr, flush=True)
        traceback.print_exc()
        return 1
    return 0


def run_master(args):
    root = Path(args.root).resolve()
    workers = [int(s) for s in args.workers.split(',')]
    if len(workers) != len(ALGOS) or any(w < 1 for w in workers):
        raise ValueError('--workers must have 6 positive counts for algos 1,2,3,5,6,7')
    if sum(workers) > 12:
        raise ValueError('Total worker count must be <= 12')
    ids = list(range(args.start, args.end + 1))
    if not ids:
        raise ValueError('Empty file range')
    # Interleave algorithms to avoid concentrating all large model instances at startup.
    queue = []
    for (algo, _), count in zip(ALGOS.items(), workers):
        for worker_i in range(min(count, len(ids))):
            assigned = ids[worker_i::count]
            if assigned:
                queue.append((algo, ','.join(map(str, assigned))))
    if args.dry_run:
        for algo, fileids in queue:
            print('ALG%s: %s' % (algo, fileids))
        print('Max processes:', len(queue))
        return 0

    # Round-robin start: faster/lighter groups can begin while heavy ALG7 is loading.
    queue.sort(key=lambda x: (int(x[1].split(',')[0]), list(ALGOS).index(x[0])))
    active = []
    results = []
    last_notice = 0.0
    try:
        while queue or active:
            for algo, ids_csv, p in active[:]:
                code = p.poll()
                if code is not None:
                    active.remove((algo, ids_csv, p))
                    results.append((algo, ids_csv, code))
                    print('[%s] ALG%s files=%s returncode=%s (%d/%d done)' % (
                        'OK' if code == 0 else 'ERROR', algo, ids_csv, code,
                        len(results), len(results) + len(active) + len(queue)), flush=True)

            if queue:
                avail = available_memory_bytes()
                if not active or avail is None or avail >= args.min_available_gb * 1024 ** 3:
                    algo, ids_csv = queue.pop(0)
                    child = [sys.executable, '-u', str(Path(__file__).resolve()),
                             '--worker', algo, '--ids', ids_csv,
                             '--root', str(root), '--codec', args.codec or 'none',
                             '--bitrate', args.bitrate]
                    # Child stdout contains only algorithm diagnostics; discard to avoid
                    # huge notebook/terminal buffers. Child errors remain visible.
                    p = subprocess.Popen(child, cwd=str(root),
                                         stdout=subprocess.DEVNULL, stderr=None,
                                         env=os.environ.copy())
                    active.append((algo, ids_csv, p))
                    print('[START] ALG%s files=%s pid=%d; active=%d' % (
                        algo, ids_csv, p.pid, len(active)), flush=True)
                    time.sleep(args.launch_gap)
                    continue
                if time.monotonic() - last_notice >= 10:
                    print('[RAM GUARD] only %.2f GiB available; %d running, %d queued'
                          % (avail / 1024 ** 3, len(active), len(queue)), flush=True)
                    last_notice = time.monotonic()
            if active or queue:
                time.sleep(1)
    except KeyboardInterrupt:
        print('\n[STOP] sending SIGTERM to workers', flush=True)
        for _, _, p in active:
            p.terminate()
        for _, _, p in active:
            try:
                p.wait(timeout=5)
            except subprocess.TimeoutExpired:
                p.kill()
        return 130
    bad = [r for r in results if r[2] != 0]
    print('Completed: %d workers, failed: %d' % (len(results), len(bad)))
    return 1 if bad else 0


def main():
    parser = argparse.ArgumentParser(description='NearS: up to 12 specialized workers, audio output only')
    parser.add_argument('--root', default=str(Path(__file__).resolve().parent))
    parser.add_argument('--codec', choices=['mp3', 'opus', 'ogg', 'none'], default='mp3')
    parser.add_argument('--bitrate', default='64k')
    parser.add_argument('--start', type=int, default=1)
    parser.add_argument('--end', type=int, default=19)
    parser.add_argument('--workers', default='2,2,2,2,2,2',
                        help='Worker counts for ALG1,2,3,5,6,7. Sum <= 12.')
    parser.add_argument('--min-available-gb', type=float, default=2.5,
                        help='Do not start additional workers below this MemAvailable')
    parser.add_argument('--launch-gap', type=float, default=3.0,
                        help='Seconds between process launches (RAM guard)')
    parser.add_argument('--dry-run', action='store_true')
    parser.add_argument('--worker', choices=list(ALGOS), help=argparse.SUPPRESS)
    parser.add_argument('--ids', help=argparse.SUPPRESS)
    args = parser.parse_args()
    args.codec = 'ogg' if args.codec in ('opus', 'ogg') else None if args.codec == 'none' else args.codec
    sys.exit(run_worker(args) if args.worker else run_master(args))


if __name__ == '__main__':
    main()
